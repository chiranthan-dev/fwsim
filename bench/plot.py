CHARTS = ["cache_mode_iops.png", "cache_mode_latency.png", "powerloss.png", "queues.png",
          "readahead_destage.png"]


def update_readme(md):
    if not os.path.exists(README):
        return
    text = open(README, encoding="utf-8").read()
    pat = re.compile(r"(<!-- RESULTS:BEGIN -->\n).*?(<!-- RESULTS:END -->)", re.S)
    if pat.search(text):
        text = pat.sub(lambda m: m.group(1) + md + "\n" + m.group(2), text)
        open(README, "w", encoding="utf-8", newline="\n").write(text)
        print("plot.py: refreshed results section of README.md")


def main():
    d = load()
    md = markdown(d)
    with open(os.path.join(OUT, "results.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# fwsim benchmark results\n\n" + md)
    print(f"plot.py: wrote {OUT}/results.md")
    try:
        plt = setup_mpl()
    except ImportError:
        print("plot.py: matplotlib not installed - skipping PNG charts")
        update_readme(md)
        return
    chart_cache_mode(plt, d)
    chart_latency(plt, d)
    chart_powerloss(plt, d)
    chart_queues(plt, d)
    chart_ra_destage(plt, d)
    print("plot.py: wrote " + ", ".join(f"{OUT}/{c}" for c in CHARTS))
    update_readme(md)


if __name__ == "__main__":
    main()
