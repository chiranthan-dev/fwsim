#!/usr/bin/env python3
"""
plot.py - turn results/results.csv (written by fwbench) into
results/results.md (markdown tables) and results/*.png charts, and refresh
the results section of README.md between the RESULTS markers.

Every number here is read from the CSV; nothing is typed in by hand.
Needs Python 3 + matplotlib (only for the PNGs; the markdown is produced
even if matplotlib is missing).
"""
import csv
import os
import re
import sys
from collections import defaultdict

OUT = sys.argv[1] if len(sys.argv) > 1 else "results"
CSV = os.path.join(OUT, "results.csv")
TRIALS = os.path.join(OUT, "powerloss_trials.csv")
README = "README.md"

# ---- palette: validated categorical slots (light surface) --------------------
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK2 = "#52514e"
MUTED = "#898781"
GRID = "#e1e0d9"
AXIS = "#c3c2b7"
S1, S2, S3, S4 = "#2a78d6", "#eb6834", "#1baf7a", "#eda100"


def load():
    data = defaultdict(dict)        # (exp, variant) -> {metric: (value, unit)}
    with open(CSV, newline="") as f:
        for r in csv.DictReader(f):
            data[(r["experiment"], r["variant"])][r["metric"]] = (float(r["value"]), r["unit"])
    return data


def v(data, exp, variant, metric, default=float("nan")):
    return data.get((exp, variant), {}).get(metric, (default, ""))[0]


def fmt(x, nd=1):
    if x != x:  # NaN
        return "-"
    if abs(x) >= 10000:
        return f"{x:,.0f}"
    if abs(x) >= 100:
        return f"{x:,.{0 if nd <= 1 else 1}f}"
    return f"{x:.{nd}f}"


# ---- markdown -------------------------------------------------------------------

WORKLOADS = [
    ("randwrite_full", "Random 4K writes, whole 100 GB disk"),
    ("randwrite_1g", "Random 4K writes, 1 GiB region"),
    ("mixed_hot", "70/30 read/write, 90% of I/O to a hot 1.6 MiB of 32 MiB"),
    ("randread_full", "Random 4K reads, whole disk"),
]
PL_MODES = [
    ("wb_noflush", "Write-back, no FLUSH"),
    ("wb_flush", "Write-back + FLUSH every 32 writes"),
    ("wb_fua", "Write-back, every write FUA"),
    ("write_through", "Write-through (cache off)"),
]


def markdown(d):
    L = []
    scale = v(d, "meta", "config", "time_scale")
    quick = v(d, "meta", "config", "quick", 0)
    L.append(f"_Generated by `make bench` from `results/results.csv`. Time scale {scale:g}: "
             f"times are drive time (wall-clock / {scale:g}) unless marked wall."
             f"{' QUICK MODE (reduced op counts).' if quick else ''}_\n")

    L.append("### Write-back vs write-through (QD 4, 2 MiB cache)\n")
    L.append("| Workload | Mode | IOPS (acked) | IOPS (incl. final FLUSH) | p50 ms | p95 ms | p99 ms | Read hit % |")
    L.append("|---|---|---:|---:|---:|---:|---:|---:|")
    for key, desc in WORKLOADS:
        for mode, label in (("write_through", "write-through"), ("write_back", "write-back")):
            var = f"{key}/{mode}"
            hit = v(d, "cache_mode", var, "read_hit_rate")
            L.append(f"| {desc} | {label} | {fmt(v(d,'cache_mode',var,'iops'))} | "
                     f"{fmt(v(d,'cache_mode',var,'iops_durable'))} | {fmt(v(d,'cache_mode',var,'lat_p50'),2)} | "
                     f"{fmt(v(d,'cache_mode',var,'lat_p95'),2)} | {fmt(v(d,'cache_mode',var,'lat_p99'),2)} | "
                     f"{fmt(hit) if hit == hit else '-'} |")
    L.append("")

    L.append("### Power loss (random 4K writes over 32 MiB, QD 4, cut at a random moment 50-1000 ms)\n")
    L.append("| Mode | Trials | Acked writes / trial | Lost acked writes / trial (avg) | max | Trials with loss | Durability violations | Write IOPS |")
    L.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for key, desc in PL_MODES:
        L.append(f"| {desc} | {fmt(v(d,'powerloss',key,'trials'),0)} | "
                 f"{fmt(v(d,'powerloss',key,'acked_writes_per_trial'))} | "
                 f"{fmt(v(d,'powerloss',key,'lost_per_trial_avg'))} | "
                 f"{fmt(v(d,'powerloss',key,'lost_per_trial_max'),0)} | "
                 f"{fmt(v(d,'powerloss',key,'trials_with_loss'),0)} | "
                 f"{fmt(v(d,'powerloss',key,'durability_violations'),0)} | "
                 f"{fmt(v(d,'powerloss',key,'write_iops_avg'))} |")
    L.append("")
    L.append("_Lost = the latest acknowledged version of a block is not on the media after reboot. "
             "Violation = data the drive promised was durable (FUA / write-through ack, or covered "
             "by a completed FLUSH) is missing. Write IOPS = acknowledged writes per second of drive time "
             "until the cut._\n")

    L.append("### Queues: mutex + condvar vs lock-free SPSC\n")
    L.append("| Measurement | mutex + condvar | lock-free SPSC | ratio |")
    L.append("|---|---:|---:|---:|")
    m = v(d, "queue_micro", "mutex_condvar", "handoff_rate_median")
    l = v(d, "queue_micro", "lockfree_spsc", "handoff_rate_median")
    L.append(f"| Raw handoff, 1 producer -> 1 consumer, median of 5 (M items/s, wall) | {fmt(m,2)} | {fmt(l,2)} | {fmt(l/m,1)}x |")
    for qd in (1, 32):
        mm = v(d, "queue_e2e", f"mutex/qd{qd}", "cmd_rate")
        ll = v(d, "queue_e2e", f"lockfree/qd{qd}", "cmd_rate")
        L.append(f"| Firmware cache-hit READs, QD {qd} (K cmds/s, wall) | {fmt(mm)} | {fmt(ll)} | {fmt(ll/mm,1)}x |")
        mm = v(d, "queue_e2e", f"mutex/qd{qd}", "lat_avg")
        ll = v(d, "queue_e2e", f"lockfree/qd{qd}", "lat_avg")
        L.append(f"| Firmware cache-hit READ latency avg, QD {qd} (us, wall) | {fmt(mm,2)} | {fmt(ll,2)} | |")
    L.append("")

    L.append("### Read-ahead and destage order\n")
    L.append("| Experiment | Variant | IOPS | IOPS (incl. FLUSH) | p50 ms | p99 ms | Read hit % |")
    L.append("|---|---|---:|---:|---:|---:|---:|")
    for exp, var, label in (("readahead", "on", "Sequential 64K reads, QD 1: read-ahead on"),
                            ("readahead", "off", "Sequential 64K reads, QD 1: read-ahead off"),
                            ("destage_order", "lba_sorted", "Random 4K writes, write-back: LBA-sorted destage"),
                            ("destage_order", "age_order", "Random 4K writes, write-back: age-order destage")):
        hit = v(d, exp, var, "read_hit_rate")
        L.append(f"| {label.split(':')[0]} | {label.split(': ')[1]} | {fmt(v(d,exp,var,'iops'))} | "
                 f"{fmt(v(d,exp,var,'iops_durable'))} | {fmt(v(d,exp,var,'lat_p50'),2)} | "
                 f"{fmt(v(d,exp,var,'lat_p99'),2)} | {fmt(hit) if hit == hit else '-'} |")
    L.append("")

    L.append("### Integrity (CRC-32 per sector, 3 retries)\n")
    crc = int(v(d, "integrity", "crc32", "check_value_123456789", 0))
    L.append(f"CRC-32(\"123456789\") = `0x{crc:08X}` (standard check value 0xCBF43926).\n")
    L.append("| Sectors read | Persistent flips injected | Transient flips injected | CRC errors detected | Recovered by retry | MEDIUM_ERROR returned (at injected LBA) | Silent corruptions |")
    L.append("|---:|---:|---:|---:|---:|---:|---:|")
    g = lambda m_: fmt(v(d, "integrity", "faults", m_), 0)
    L.append(f"| {g('sectors_read')} | {g('persistent_flips_injected')} | {g('transient_flips_injected')} | "
             f"{g('crc_errors_detected')} | {g('recovered_by_retry')} | {g('medium_errors_returned')} "
             f"({g('medium_errors_at_injected_lba')}) | {g('silent_corruptions')} |")
    L.append("")
    return "\n".join(L)


# ---- charts --------------------------------------------------------------------------

def setup_mpl():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.sans-serif": ["DejaVu Sans", "Arial", "sans-serif"],
        "font.size": 10,
        "axes.facecolor": SURFACE, "figure.facecolor": SURFACE,
        "axes.edgecolor": AXIS, "axes.labelcolor": INK2,
        "xtick.color": MUTED, "ytick.color": MUTED,
        "text.color": INK, "axes.titlecolor": INK,
        "axes.titlesize": 11, "axes.titleweight": "bold", "axes.titlelocation": "left",
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8, "grid.linestyle": "-",
        "axes.axisbelow": True, "legend.frameon": False, "savefig.dpi": 150,
    })
    return plt


def bar_labels(ax, bars, values, nd=0, horizontal=False):
    for b, val in zip(bars, values):
        if val != val:
            continue
        text = f"{val:,.{nd}f}"
        if horizontal:
            ax.annotate(text, (b.get_width(), b.get_y() + b.get_height() / 2), xytext=(4, 0),
                        textcoords="offset points", va="center", ha="left", fontsize=8.5, color=INK2)
        else:
            ax.annotate(text, (b.get_x() + b.get_width() / 2, b.get_height()), xytext=(0, 3),
                        textcoords="offset points", ha="center", va="bottom", fontsize=8.5, color=INK2)


def chart_cache_mode(plt, d):
    import numpy as np
    labels = ["Random writes\nwhole disk", "Random writes\n1 GiB", "Mixed 70/30\nhot set", "Random reads\nwhole disk"]
    keys = [k for k, _ in WORKLOADS]
    wt = [v(d, "cache_mode", f"{k}/write_through", "iops_durable") for k in keys]
    wb = [v(d, "cache_mode", f"{k}/write_back", "iops_durable") for k in keys]
    x = np.arange(len(keys))
    w = 0.34
    fig, ax = plt.subplots(figsize=(8, 4.2))
    b1 = ax.bar(x - w / 2 - 0.01, wt, w, color=S1, label="write-through")
    b2 = ax.bar(x + w / 2 + 0.01, wb, w, color=S2, label="write-back")
    bar_labels(ax, b1, wt)
    bar_labels(ax, b2, wb)
    ax.set_xticks(x, labels)
    ax.set_ylabel("IOPS, drive time (incl. final FLUSH)")
    ax.set_title("Write-back caching vs write-through, QD 4")
    ax.grid(axis="x", visible=False)
    ax.legend(loc="upper right", ncols=2)
    ax.set_ylim(0, max(wt + wb) * 1.18)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "cache_mode_iops.png"))
    plt.close(fig)


def chart_latency(plt, d):
    from matplotlib.ticker import FuncFormatter
    keys = [k for k, _ in WORKLOADS]
    names = ["Random writes, whole disk", "Random writes, 1 GiB", "Mixed 70/30, hot set", "Random reads, whole disk"]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax, metric, title, log in ((axes[0], "lat_p50", "Median (p50) latency", True),
                                   (axes[1], "lat_p99", "p99 latency", False)):
        for i, k in enumerate(keys):
            a = v(d, "cache_mode", f"{k}/write_through", metric)
            b = v(d, "cache_mode", f"{k}/write_back", metric)
            y = len(keys) - 1 - i
            ax.plot([a, b], [y, y], color=GRID, lw=2, zorder=1)
            ax.scatter([a], [y], s=70, color=S1, edgecolor=SURFACE, linewidth=2, zorder=3,
                       label="write-through" if i == 0 else None)
            ax.scatter([b], [y], s=70, color=S2, edgecolor=SURFACE, linewidth=2, zorder=3,
                       label="write-back" if i == 0 else None)
        if log:   # p50 spans 0.03 ms (cache) to 50 ms (seek): needs log
            ax.set_xscale("log")
            ax.xaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:g}"))
            ax.xaxis.set_minor_formatter(FuncFormatter(lambda x, _: ""))
            ax.set_xlabel("ms, drive time (log scale)")
        else:
            ax.set_xlim(left=0)
            ax.set_xlabel("ms, drive time")
        ax.set_title(title)
        ax.grid(axis="y", visible=False)
    axes[0].set_yticks(range(len(keys)), list(reversed(names)))
    axes[0].legend(loc="lower left")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "cache_mode_latency.png"))
    plt.close(fig)


def chart_powerloss(plt, d):
    import numpy as np
    per_mode = defaultdict(list)
    if os.path.exists(TRIALS):
        with open(TRIALS, newline="") as f:
            for r in csv.DictReader(f):
                per_mode[r["mode"]].append(r)
    keys = [k for k, _ in PL_MODES]
    labels = ["Write-back\nno FLUSH", "Write-back\n+ FLUSH", "Write-back\n+ FUA", "Write-\nthrough"]
    colors = [S1, S2, S3, S4]
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2))
    ax = axes[0]
    rng = np.random.default_rng(0)
    for i, k in enumerate(keys):
        lost = [int(r["lost"]) for r in per_mode.get(k, [])]
        if not lost:
            continue
        jitter = rng.uniform(-0.18, 0.18, len(lost))
        ax.scatter(np.full(len(lost), i) + jitter, lost, s=16, color=colors[i], alpha=0.75,
                   edgecolor="none")
        avg = sum(lost) / len(lost)
        ax.plot([i - 0.3, i + 0.3], [avg, avg], color=INK, lw=2)
        ax.annotate(f"avg {avg:,.1f}", (i, max(lost)), xytext=(0, 6), textcoords="offset points",
                    ha="center", va="bottom", fontsize=8.5, color=INK2)
    ax.set_xticks(range(len(keys)), labels)
    ax.set_xlim(-0.6, len(keys) - 0.4)
    ax.set_ylim(top=ax.get_ylim()[1] * 1.08)
    ax.set_ylabel("acknowledged writes lost per trial")
    ax.set_title("Acknowledged writes lost at power loss")
    ax.grid(axis="x", visible=False)

    ax = axes[1]
    iops = [v(d, "powerloss", k, "write_iops_avg") for k in keys]
    bars = ax.bar(range(len(keys)), iops, 0.5, color=colors)
    bar_labels(ax, bars, iops)
    ax.set_xticks(range(len(keys)), labels)
    ax.set_ylabel("acked write IOPS, drive time")
    ax.set_title("...and what durability costs")
    ax.grid(axis="x", visible=False)
    ax.set_ylim(0, max(iops) * 1.15)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "powerloss.png"))
    plt.close(fig)


def chart_queues(plt, d):
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6))
    ax = axes[0]
    vals = [v(d, "queue_micro", "mutex_condvar", "handoff_rate_median"),
            v(d, "queue_micro", "lockfree_spsc", "handoff_rate_median")]
    bars = ax.barh([1, 0], vals, 0.45, color=[S1, S2])
    bar_labels(ax, bars, vals, nd=1, horizontal=True)
    ax.set_yticks([1, 0], ["mutex + condvar", "lock-free SPSC"])
    ax.set_xlabel("million items / s (wall)")
    ax.set_title("Raw queue handoff (2 threads)")
    ax.grid(axis="y", visible=False)
    ax.set_xlim(0, max(vals) * 1.25)

    ax = axes[1]
    import numpy as np
    x = np.arange(2)
    w = 0.34
    mu = [v(d, "queue_e2e", f"mutex/qd{q}", "cmd_rate") for q in (1, 32)]
    lf = [v(d, "queue_e2e", f"lockfree/qd{q}", "cmd_rate") for q in (1, 32)]
    b1 = ax.bar(x - w / 2 - 0.01, mu, w, color=S1, label="mutex + condvar")
    b2 = ax.bar(x + w / 2 + 0.01, lf, w, color=S2, label="lock-free SPSC")
    bar_labels(ax, b1, mu)
    bar_labels(ax, b2, lf)
    ax.set_xticks(x, ["QD 1", "QD 32"])
    ax.set_ylabel("K commands / s (wall)")
    ax.set_title("Firmware command rate, cache hits")
    ax.grid(axis="x", visible=False)
    ax.legend(loc="upper left")
    ax.set_ylim(0, max(mu + lf) * 1.25)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "queues.png"))
    plt.close(fig)


