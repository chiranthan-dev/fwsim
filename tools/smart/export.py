"""export.py - turn the trained logistic regression into firmware tables.

    python tools/smart/export.py results/smart/model_deploy.json \
        results/smart/vectors.csv src/smart_model.h tests/smart_vectors.h

The firmware never sees a float. Inference is:

    acc      = sum_i W[i] * (f[i] - ZP[i])            int16 x int16 -> int32
    logit_q8 = floor((acc * MULT + BIAS) / 2^SHIFT)   int64, logit in 1/256
    risk_bp  = sigmoid LUT (257 points over [-16, 16], linear interpolation)
               -> P(fail within 30 days) in basis points (1/10000)
    flag     = logit_q8 >= THRESH_Q8

The StandardScaler is folded into the weights (w' = w / sigma), the
weights are quantised to WEIGHT_BITS-bit integers with ONE scale (16 by
default; 8 is available and agree.py reports what it would cost: on this
model up to ~0.2 in log-odds for drives with large counters, where the
sigmoid is steep - 17 extra bytes buy that back), and the prior shift that
undoes the balanced class weights goes into BIAS. ZP[i] (the training mean,
rounded) is an integer zero point: the weight rounding error grows with
|f - ZP|, so centring keeps features that are large but nearly constant
(log power-on hours ~230, temperature ~35) from dominating it. Subtracting
an integer and folding w' * ZP into BIAS is exact.

int_logit_q8()/risk_bp() below are the bit-exact Python reference that
tests and agree.py compare the C code against.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

SHIFT = 32
WEIGHT_BITS = 16
LUT_N = 257
LUT_LO_Q8 = -16 * 256       # logit -16
LUT_STEP_SHIFT = 5          # 32 q8 units = 1/8 logit per LUT step


def quantize(model: dict, bits: int = WEIGHT_BITS) -> dict:
    mean = np.asarray(model["mean"])
    scale = np.asarray(model["scale"])
    coef = np.asarray(model["coef"])
    w = coef / scale                                    # per raw feature
    zp = np.round(mean).astype(np.int64)
    # logit = w.(f - mean) + c = w.(f - zp) + w.(zp - mean) + c
    b = (model["intercept"] + float(np.sum(w * (zp - mean))) + model["prior_logit_shift"])
    qmax = (1 << (bits - 1)) - 1
    s = float(np.max(np.abs(w))) / qmax
    q = np.clip(np.round(w / s), -qmax, qmax).astype(np.int64)
    mult = int(round(s * 256 * (1 << SHIFT)))
    bias = int(round(b * 256 * (1 << SHIFT)))
    thr = model["threshold_logit"] + model["prior_logit_shift"]
    xs = (np.arange(LUT_N) * (1 << LUT_STEP_SHIFT) + LUT_LO_Q8) / 256.0
    lut = np.round(10000.0 / (1.0 + np.exp(-xs))).astype(np.int64)
    return {"bits": bits, "w": q, "zp": zp, "mult": mult, "bias": bias, "thresh_q8": int(round(thr * 256)),
            "lut": lut, "float_w": w, "float_b": b, "float_thr": thr, "scale": s}


def int_logit_q8(X: np.ndarray, qm: dict) -> np.ndarray:
    acc = (np.asarray(X, dtype=np.int64) - qm["zp"]) @ qm["w"]
    return (acc * qm["mult"] + qm["bias"]) >> SHIFT      # >> on int64 = floor


def risk_bp(logit_q8: np.ndarray, qm: dict) -> np.ndarray:
    lut = qm["lut"]
    t = np.clip(np.asarray(logit_q8, dtype=np.int64) - LUT_LO_Q8, 0,
                (LUT_N - 1) << LUT_STEP_SHIFT)
    i = t >> LUT_STEP_SHIFT
    frac = t & ((1 << LUT_STEP_SHIFT) - 1)
    j = np.minimum(i + 1, LUT_N - 1)
    return lut[i] + (((lut[j] - lut[i]) * frac) >> LUT_STEP_SHIFT)


def model_id(qm: dict) -> int:
    h = hashlib.sha256()
    for k in ("w", "zp", "lut"):
        h.update(np.asarray(qm[k], dtype=np.int64).tobytes())
    for k in ("mult", "bias", "thresh_q8"):
        h.update(str(qm[k]).encode())
    return int(h.hexdigest()[:8], 16)


def c_array(vals, per_line=12, width=6) -> str:
    vals = [str(int(v)) for v in vals]
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(v.rjust(width) for v in vals[i:i + per_line]) + ",")
    return "\n".join(lines)


def write_model_header(path: str, model: dict, qm: dict) -> None:
    feats = model["features"]
    w_lines = "\n".join(f"    {int(q):6d},   /* {f:<10s} float w = {fw:+.6f} */"
                        for q, f, fw in zip(qm["w"], feats, qm["float_w"]))
    src = f"""/*
 * smart_model.h - GENERATED by tools/smart/export.py. Do not edit.
 *
 * Logistic regression predicting "this drive fails within 30 days",
 * trained on Backblaze Drive Stats {", ".join(model["quarters"])}
 * ({model["trained_on"]}).
 * Features: see SMART_FEATURE_NAMES and src/smart.c (smart_features()).
 *
 * Integer-only inference (no FPU, no malloc):
 *   acc      = sum W[i] * (f[i] - ZP[i])
 *   logit_q8 = floor((acc * SMART_MODEL_MULT + SMART_MODEL_BIAS) >> SMART_MODEL_SHIFT)
 *   risk_bp  = SMART_SIGMOID_LUT, linear interpolation (basis points)
 *   flag     = logit_q8 >= SMART_MODEL_THRESH_Q8
 * Weight scale {qm["scale"]:.6g} per int{qm["bits"]} step; float bias {qm["float_b"]:+.6f};
 * threshold logit {qm["float_thr"]:+.4f} (1% drive-level false alarms on
 * a 31-day window of the training period).
 */
#ifndef FWSIM_SMART_MODEL_H
#define FWSIM_SMART_MODEL_H

#include <stdint.h>

#define SMART_MODEL_NFEAT     {len(feats)}
#define SMART_MODEL_ID        0x{model_id(qm):08X}u
#define SMART_MODEL_SHIFT     {SHIFT}
#define SMART_MODEL_MULT      INT64_C({qm["mult"]})
#define SMART_MODEL_BIAS      INT64_C({qm["bias"]})
#define SMART_MODEL_THRESH_Q8 {qm["thresh_q8"]}
#define SMART_LUT_N           {LUT_N}
#define SMART_LUT_LO_Q8       ({LUT_LO_Q8})
#define SMART_LUT_STEP_SHIFT  {LUT_STEP_SHIFT}

static const char *const SMART_FEATURE_NAMES[SMART_MODEL_NFEAT] = {{
{c_array_str(feats)}
}};

#define SMART_MODEL_WEIGHT_BITS {qm["bits"]}
static const int{qm["bits"]}_t SMART_MODEL_W[SMART_MODEL_NFEAT] = {{
{w_lines}
}};

/* Integer zero points (training means): see export.py. */
static const int16_t SMART_MODEL_ZP[SMART_MODEL_NFEAT] = {{
{c_array(qm["zp"], 9, 5)}
}};

/* round(10000 * sigmoid(-16 + k/8)), k = 0 .. {LUT_N - 1} */
static const uint16_t SMART_SIGMOID_LUT[SMART_LUT_N] = {{
{c_array(qm["lut"], 12, 5)}
}};

#endif
"""
    write_if_changed(path, src)


def c_array_str(names) -> str:
    return "\n".join(f'    "{n}",' for n in names)


def write_vectors_header(path: str, vec: pd.DataFrame, model: dict, qm: dict) -> None:
    feats = model["features"]
    X = vec[feats].to_numpy(dtype=np.int64)
    lq = int_logit_q8(X, qm)
    rb = risk_bp(lq, qm)
    fz = vec["float_logit"].to_numpy() + model["prior_logit_shift"]
    fp_bp = np.round(10000.0 / (1.0 + np.exp(-fz))).astype(np.int64)
    rows = "\n".join(
        "    {{ {{{}}}, {}, {}, {} }},".format(", ".join(str(int(v)) for v in x), int(a), int(b), int(c))
        for x, a, b, c in zip(X, lq, rb, fp_bp))
    src = f"""/*
 * smart_vectors.h - GENERATED by tools/smart/export.py. Do not edit.
 *
 * {len(X)} feature rows from the Backblaze TEST window, with the Python
 * integer reference (logit_q8, risk_bp) and the float scikit-learn model's
 * probability (float_bp). test_smart.c checks the C model reproduces the
 * integers exactly and the float model within tolerance.
 */
#ifndef FWSIM_SMART_VECTORS_H
#define FWSIM_SMART_VECTORS_H

#include <stdint.h>

#include "smart_model.h"

#define SMART_VECTORS_MODEL_ID 0x{model_id(qm):08X}u
#define SMART_VECTORS_N {len(X)}

typedef struct {{
    int16_t f[SMART_MODEL_NFEAT];
    int32_t logit_q8;
    int32_t risk_bp;
    int32_t float_bp;
}} smart_vector_t;

static const smart_vector_t SMART_VECTORS[SMART_VECTORS_N] = {{
{rows}
}};

#endif
"""
    write_if_changed(path, src)


def write_if_changed(path: str, src: str) -> None:
    """Keep the file's mtime when nothing changed (no needless rebuilds)."""
    try:
        with open(path, newline="") as fh:
            if fh.read() == src:
                return
    except FileNotFoundError:
        pass
    with open(path, "w", newline="\n") as fh:
        fh.write(src)


def main() -> int:
    if len(sys.argv) != 5:
        print(__doc__, file=sys.stderr)
        return 2
    mpath, vpath, hpath, tpath = sys.argv[1:]
    with open(mpath) as fh:
        model = json.load(fh)
    qm = quantize(model)
    vec = pd.read_csv(vpath)
    write_model_header(hpath, model, qm)
    write_vectors_header(tpath, vec, model, qm)
    X = vec[model["features"]].to_numpy(dtype=np.int64)
    fz = vec["float_logit"].to_numpy() + model["prior_logit_shift"]
    iz = int_logit_q8(X, qm) / 256.0
    print(f"export: {len(model['features'])} int{qm['bits']} weights, model id 0x{model_id(qm):08X}; "
          f"vectors max |int - float logit| = {np.max(np.abs(iz - fz)):.4f} -> {hpath}, {tpath}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
