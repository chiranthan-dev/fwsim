"""report.py - results/smart/*.{json,csv} -> results/smart/results.md

    python tools/smart/report.py results/smart

Every number in the README's SMART section comes from this file.
"""
from __future__ import annotations

import csv
import json
import math
import os
import sys

NAMES = {
    "baseline": "Baseline rule, graded (sum of raw 5/187/188/197/198)",
    "lr_deploy": "Logistic regression, deployable features (in fwsim)",
    "lr_full": "Logistic regression, all features",
    "gbt": "Gradient-boosted trees (60 x depth 3), all features",
}


def pct(x) -> str:
    return "-" if x is None or x != x else f"{100 * float(x):.1f}%"


def f3(x) -> str:
    return "-" if x is None or x != x else f"{float(x):.3f}"


def ci(r, k) -> str:
    v = r.get(k)
    return f" ({100 * v[0]:.0f}-{100 * v[1]:.0f}%)" if v else ""


def ci3(r, k) -> str:
    v = r.get(k)
    return f" ({v[0]:.3f}-{v[1]:.3f})" if v else ""


def main() -> int:
    out = sys.argv[1]
    with open(os.path.join(out, "summary.json")) as fh:
        s = json.load(fh)
    agree = {}
    if os.path.exists(os.path.join(out, "agreement.json")):
        with open(os.path.join(out, "agreement.json")) as fh:
            agree = json.load(fh)
    inf = {}
    if os.path.exists(os.path.join(out, "inference.csv")):
        with open(os.path.join(out, "inference.csv")) as fh:
            inf = {r["metric"]: r["value"] for r in csv.DictReader(fh)}
    with open(os.path.join(out, "by_manufacturer.csv")) as fh:
        mfr = list(csv.DictReader(fh))

    d = s["data"]
    L = []
    L.append("# SMART failure prediction: results\n")
    L.append(f"_Generated by `make bench-smart` (tools/smart/report.py). Data: Backblaze Drive "
             f"Stats {', '.join(d['quarters'])} ({d['first_day']} .. {d['last_day']}), data HDDs "
             f"of 4 TB and up. Label: the drive fails within {d['horizon_days']} days. Unit: "
             f"one drive over the test window (flagged if any day's score crosses the "
             f"threshold). False-alarm rate = healthy drives flagged / healthy drives._\n")
    for sname in ("serial", "time"):
        sp = s["splits"][sname]
        m = sp["metrics"]
        rule = m["rule"]
        L.append(f"## {sname} split: {sp['desc']}\n")
        L.append(f"{sp['test_drives']:,} test drives, {sp['test_failed_drives']:,} failed "
                 f"(positive rate {pct(sp['test_failed_drives'] / sp['test_drives'])}). "
                 f"Training: {sp['train_rows']:,} drive-days ({sp['train_pos_rows']:,} positive).\n")
        L.append(f"Baseline rule (any raw > 0) as a single operating point: recall "
                 f"**{pct(rule['recall'])}** at **{pct(rule['far'])}** false alarms "
                 f"(precision {pct(rule['precision'])}, {rule['tp']} of {rule['pos']} failures "
                 f"caught, {rule['fp']:,} healthy drives flagged).\n")
        L.append(f"| Model | PR-AUC (95% CI) | Recall at 1% false alarms (95% CI) | "
                 f"Recall at the rule's {pct(rule['far'])} false alarms |")
        L.append("|---|---:|---:|---:|")
        for k in ("baseline", "lr_deploy", "lr_full", "gbt"):
            r = m[k]
            L.append(f"| {NAMES[k]} | {f3(r['pr_auc'])}{ci3(r, 'pr_auc_ci')} | "
                     f"{pct(r['recall_at_far'])}{ci(r, 'recall_at_far_ci')} | "
                     f"{pct(r['recall_at_rule_far'])} |")
        L.append("")
        if sname == "time" and "deployed_threshold" in sp:
            dt = sp["deployed_threshold"]
            t = dt["test"]
            with open(os.path.join(out, "model_deploy.json")) as fh:
                cal = dt["logit"] + json.load(fh)["prior_logit_shift"]
            L.append(f"Deployed threshold (chosen for 1% false alarms on a 31-day window of the "
                     f"TRAINING period, never the test set; log-odds {cal:+.2f}, i.e. flag at a "
                     f"predicted {100 / (1 + math.exp(-cal)):.1f}% chance of failing within 30 "
                     f"days): on the test window recall "
                     f"**{pct(t['recall'])}** at **{pct(t['far'])}** false alarms "
                     f"(precision {pct(t['precision'])}).\n")
        L.append(f"![PR curves, {sname} split](pr_{sname}.png)\n")

    L.append("## Per manufacturer (test drives)\n")
    for sname in ("serial", "time"):
        L.append(f"### {sname} split\n")
        L.append("| Group | Drives | Failed | Rule recall / false alarms | LR-deploy PR-AUC | "
                 "LR-full PR-AUC | GBT PR-AUC | Graded-rule recall @1% | LR-deploy recall @1% | "
                 "GBT recall @1% |")
        L.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        for r in mfr:
            if r["split"] != sname:
                continue
            g = r["group"] if r["kind"] == "mfr" else f"&nbsp;&nbsp;Toshiba {r['group']}"
            L.append(f"| {g} | {int(r['drives']):,} | {r['failed']} | "
                     f"{pct(float(r['rule_recall']))} / {pct(float(r['rule_far']))} | "
                     f"{f3(float(r['lr_deploy_pr_auc']))} | {f3(float(r['lr_full_pr_auc']))} | "
                     f"{f3(float(r['gbt_pr_auc']))} | {pct(float(r['baseline_recall_at_1pct']))} | "
                     f"{pct(float(r['lr_deploy_recall_at_1pct']))} | "
                     f"{pct(float(r['gbt_recall_at_1pct']))} |")
        L.append("")
    L.append("\"Recall @1%\" here uses each group's own 1%-false-alarm threshold. Groups with few "
             "failures have wide error bars; treat their numbers as indicative.\n")

    if agree:
        L.append("## C firmware vs Python (time-split test set)\n")
        L.append(f"- rows scored: {agree['rows']:,}")
        L.append(f"- C logit identical to the Python integer reference: "
                 f"**{agree['c_vs_python_int_logit_identical_pct']:.4f}%**")
        L.append(f"- predicted-failure flag, C vs float scikit-learn: "
                 f"**{agree['c_vs_float_flag_agree_pct']:.4f}%** agree "
                 f"({agree['flag_disagreements']} rows differ)")
        L.append(f"- quantisation error vs float: max |logit| {agree['max_abs_logit_diff_vs_float']:.4f} "
                 f"(mean {agree['mean_abs_logit_diff_vs_float']:.4f}); max |probability| "
                 f"{agree['max_abs_prob_diff_vs_float']:.5f} (weights: int{agree.get('weight_bits', '?')})")
        if "int8_max_abs_logit_diff_vs_float" in agree:
            L.append(f"- the same model with int8 weights would cost max |logit| "
                     f"{agree['int8_max_abs_logit_diff_vs_float']:.3f}, max |probability| "
                     f"{agree['int8_max_abs_prob_diff_vs_float']:.4f}, flag agreement "
                     f"{agree['int8_flag_agree_pct']:.4f}%; int16 costs 17 bytes more")
        L.append("")
    if inf:
        L.append("## Model size and inference time\n")
        L.append(f"- model tables: **{inf['model_bytes']} bytes** ({inf['weights_bytes']} B "
                 f"int{inf.get('weight_bits', '?')} weights + {inf.get('zp_bytes', '?')} B zero "
                 f"points + {inf['lut_bytes']} B sigmoid LUT + constants); per-drive state "
                 f"{inf['state_bytes']} bytes (32-day history)")
        L.append(f"- GBT for comparison: {s.get('gbt_nodes', '?')} tree nodes (not exported)")
        L.append(f"- **host CPU** (x86-64 under WSL2, not a drive controller): "
                 f"logit {float(inf['host_ns_logit']):.1f} ns/call, logit + risk "
                 f"{float(inf['host_ns_logit_risk']):.1f} ns, features + logit + risk "
                 f"{float(inf['host_ns_features_logit_risk']):.1f} ns\n")
    L.append("## Deployment demo (synthetic counters)\n")
    L.append("![risk timeline](demo_timeline.png)\n")
    L.append("The demo's defects are scripted; it shows the firmware pipeline works, not how "
             "accurate the model is. Accuracy claims come only from the tables above.\n")
    with open(os.path.join(out, "results.md"), "w", newline="\n") as fh:
        fh.write("\n".join(L))
    print(f"report: {os.path.join(out, 'results.md')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
